/** A lit pixel of the 64 x 64 screen. */
export interface Pixel {
  x: number;
  y: number;
}

/**
 * The lit pixels of one line of text, from the top left corner of its first glyph: each glyph 5 x 7
 * cells of scale x scale pixels, one glyph every 6 x scale pixels. A character the font lacks is
 * drawn as a space (tests/unit/pixelFont.spec.ts checks that every screen string is covered).
 */
export function layoutText(text: string, scale: 1 | 2): Pixel[] {
  const out: Pixel[] = [];
  [...text].forEach((ch, i) => {
    (GLYPHS[ch] ?? []).forEach((row, r) => {
      [...row].forEach((cell, c) => {
        if (cell !== '#') return;
        for (let dy = 0; dy < scale; dy++)
          for (let dx = 0; dx < scale; dx++) out.push({ x: i * 6 * scale + c * scale + dx, y: r * scale + dy });
      });
    });
  });
  return out;
}

/** How wide a line of text is drawn, in pixels (no space after its last glyph). */
export function textWidth(text: string, scale: 1 | 2): number {
  const n = [...text].length;
  return n ? (n * 6 - 1) * scale : 0;
}

/**
 * Pixels as the `d` of one SVG path of unit squares, moved by (dx, dy): each run of lit pixels on a
 * row is one rectangle, row by row from the top.
 */
export function pixelPath(pixels: readonly Pixel[], dx = 0, dy = 0): string {
  const rows = new Map<number, number[]>();
  for (const { x, y } of pixels) rows.set(y, [...(rows.get(y) ?? []), x]);
  let d = '';
  for (const y of [...rows.keys()].sort((a, b) => a - b)) {
    const xs = [...new Set(rows.get(y))].sort((a, b) => a - b);
    for (let i = 0; i < xs.length; ) {
      const start = xs[i] ?? 0;
      let end = start;
      while (xs[i + 1] === end + 1) {
        end++;
        i++;
      }
      i++;
      const w = end - start + 1;
      d += `M${start + dx} ${y + dy}h${w}v1h-${w}z`;
    }
  }
  return d;
}
